#!/usr/bin/env python3
"""Generate /fr/ from index.html; preview the exact diff before writing.

Run: python3 scripts/build_french.py --check (CI)
     python3 scripts/build_french.py --diff  (review)
     python3 scripts/build_french.py --write (save reviewed output)
Only Python's standard library is required.
"""
import argparse
import difflib
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VOID = set('area base br col embed hr img input link meta param source track wbr'.split())


class FrenchParser(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=False)
        self.source = source
        self.lines = [0]
        for match in re.finditer('\n', source):
            self.lines.append(match.end())
        self.stack = []
        self.edits = []

    def position(self):
        line, column = self.getpos()
        return self.lines[line - 1] + column

    def handle_starttag(self, tag, attrs):
        if tag in VOID:
            return
        attrs = dict(attrs)
        # An outer translated element owns all of its inner HTML.
        parent_translated = any(item[3] for item in self.stack)
        translation = attrs.get('data-fr') if not parent_translated else None
        self.stack.append((tag, self.position() + len(self.get_starttag_text()),
                           translation, parent_translated or translation is not None))

    def handle_startendtag(self, tag, attrs):
        pass

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        if not self.stack or self.stack[-1][0] != tag:
            raise ValueError('Unbalanced HTML at ' + str(self.getpos()) + ': ' + tag)
        _, start, translation, _ = self.stack.pop()
        if translation is not None:
            self.edits.append((start, self.position(), translation))

    def translated(self):
        self.feed(self.source)
        self.close()
        if self.stack:
            raise ValueError('Unclosed HTML tags')
        result = self.source
        for start, end, text in sorted(self.edits, reverse=True):
            result = result[:start] + text + result[end:]
        return result


def render(source):
    result = FrenchParser(source).translated()
    result = result.replace('<html lang="en-CA">', '<html lang="fr-CA">')
    result = result.replace('OLV007 - Olive Brine for the Dirty Martini',
                            "OLV007 - Saumure d’olive pour le Dirty Martini")
    description = ('OLV007 est une saumure d’olive Kalamata grecque double-filtrée, conçue pour le dirty martini. '
                   'Servie dans plus de 100 bars et restaurants. '
                   'Fabriquée à Kalamata, en Grèce · Marque montréalaise depuis 2023.')
    result = re.sub(r'(<meta (?:name="description"|property="og:description") content=")[^"]*(" />)',
                    lambda m: m[1] + description + m[2], result)
    result = result.replace('rel="canonical" href="https://www.olv007.com/"',
                            'rel="canonical" href="https://www.olv007.com/fr/"')
    result = result.replace('property="og:url" content="https://www.olv007.com/"',
                            'property="og:url" content="https://www.olv007.com/fr/"')
    result = result.replace('property="og:locale" content="en_CA"', 'property="og:locale" content="fr_CA"')
    result = result.replace('property="og:locale:alternate" content="fr_CA"', 'property="og:locale:alternate" content="en_CA"')
    result = result.replace('id="langToggle" href="/fr/" lang="fr-CA" hreflang="fr-CA" aria-label="Passer au français">FR</a>',
                            'id="langToggle" href="/" lang="en-CA" hreflang="en-CA" aria-label="Switch to English">EN</a>')
    for english, french in {
        'OLV007 trademark home': 'OLV007 — accueil',
        'OLV007 on Instagram': 'OLV007 sur Instagram',
        'Play background music': 'Activer la musique',
        'Background music': 'Musique de fond',
        'Music volume': 'Volume de la musique',
        'OLV007 in motion': 'OLV007 en mouvement',
    }.items():
        result = result.replace('"' + english + '"', '"' + french + '"')
    return '<!-- Generated by scripts/build_french.py; edit index.html, then regenerate. -->\n' + result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--diff', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'fr/index.html'
    output = render((ROOT / 'index.html').read_text())
    previous = target.read_text() if target.exists() else ''
    if args.check:
        if output != previous:
            raise SystemExit('French page is stale. Review --diff, then run --write.')
        print('French page matches index.html.')
    elif args.diff:
        print(''.join(difflib.unified_diff(previous.splitlines(True), output.splitlines(True),
                                         fromfile='a/fr/index.html', tofile='b/fr/index.html')), end='')
    else:
        target.parent.mkdir(exist_ok=True)
        target.write_text(output)
        print('Generated fr/index.html')


if __name__ == '__main__':
    main()
